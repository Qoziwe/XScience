/** §15.1 — объяснение риска и затухания. */
export function explain(p: AnalysisParams, s: Scores): { why: string; whyExt: string } {
  const t = s.t;
  const parts: string[] = [];
  if (t.mat === 3) parts.push(`${MAT[p.material].label.toLowerCase()} — легковоспламеняемый материал`);
  if (t.o2 === 3) parts.push(`кислород выше нормы (${f1(p.o2)} %)`);
  if (t.flow === 3) parts.push(`поток ${f1(p.flow)} см/с активно подпитывает пламя`);
  if (t.temp >= 2) parts.push(`высокая температура в зоне горения (${p.temp} °C)`);
  if (t.time >= 2) parts.push(`длительное горение (${p.time} с)`);
  if (t.grav === 1) parts.push('микрогравитация повышает неопределённость поведения пламени');

  const why = parts.length
    ? `Риск повышают: ${parts.join('; ')}.`
    : 'Все составляющие на минимальных значениях — условия не поддерживают развитие пламени.';

  const e: string[] = [];
  if (t.od >= 2) e.push(`недостаток кислорода (${f1(p.o2)} %)`);
  if (t.lf >= 1) e.push(p.flow === 0 ? 'отсутствие потока' : 'слабый поток');
  if (t.th >= 2) e.push(`тонкий материал (${f1(p.thickness)} мм)`);

  const whyExt = `Затухание: ${EXT_LEVEL_RU[s.extLevel].toLowerCase()} вероятность${
    e.length ? ' — ' + e.join(', ') : ', факторов затухания нет'
  }.`;

  return { why, whyExt };
}

/**
 * §15.2 — заключение. Везде говорит «для сектора»
 * (неточность прототипа «для модуля» исправлена по указанию спецификации).
 */
export function summaryOf(s: Scores): string {
  if (s.level === 'high' && s.extLevel === 'high')
    return 'Горение нестабильно: условия одновременно поддерживают быстрое распространение и срыв пламени. Нужен контроль — после срыва возможно повторное воспламенение.';
  if (s.level === 'high')
    return 'Сочетание материала, кислорода и потока создаёт условия для быстрого распространения пламени. Затухание маловероятно — требуется вмешательство.';
  if (s.level === 'medium')
    return 'Отдельные параметры повышают опасность, но условия для устойчивого быстрого горения не сложились. Достаточно наблюдения и устранения ведущего фактора.';
  return 'Все составляющие на минимальных значениях. Угрозы для сектора при текущих показаниях нет.';
}

