/**
 * §15.3–15.4 — ЕДИНЫЙ генератор рекомендаций.
 * Используется окном рекомендаций, отчётом и блоком «Рекомендуемые действия»
 * (там показываются первые 3 шага). Второго, «короткого» генератора нет.
 */
export function recommendations(
  p: AnalysisParams,
  s: Scores,
  sectorId: SectorId,
  v: Level,
): Recommendations {
  const sec = SEC[sectorId];
  const electrical = p.material === 'wire_insulation' || sectorId === 'ep';
  const st: [string, string][] = [];

  if (electrical)
    st.push([
      'Обесточьте линию и источник нагрева',
      'Горение электропроводки поддерживается током: пока линия под напряжением, тушение малоэффективно.',
    ]);
  else if (s.t.temp >= 2)
    st.push([
      'Отключите источник нагрева',
      `Температура ${p.temp} °C в зоне горения ускоряет прогрев материала.`,
    ]);

  if (s.t.o2 === 3 || s.t.flow === 3)
    st.push([
      'Снизьте приток кислорода',
      'Остановите вентиляцию сектора и подачу O₂, перекройте воздуховоды.',
    ]);

  if (v !== 'low') st.push(SECTOR_ACTION[sectorId]);

  if (s.level === 'high')
    st.push([
      'Изолируйте очаг',
      'Отделите горючие материалы от очага, не допускайте переноса пламени в соседние сектора.',
    ]);

  if (v !== 'low')
    st.push([
      'Примените подходящий способ тушения',
      electrical
        ? 'Для электрооборудования — только неводное средство.'
        : 'Выберите средство по типу материала.',
    ]);

  if (s.extLevel === 'high' && v !== 'low')
    st.push([
      'Не снимайте наблюдение после срыва пламени',
      'Пламя нестабильно: возможно повторное воспламенение.',
    ]);

  if (v === 'low')
    st.push([
      'Продолжайте наблюдение',
      'Условия в секторе не поддерживают развитие пламени, действий не требуется.',
    ]);

  st.push([
    'Подтвердите приём отчёта на Земле',
    'Отчёт передаётся автоматически; сообщите о принятых мерах.',
  ]);

  return {
    intro:
      `Сектор ${sec.code}: ${VERDICT_RU[v].toLowerCase()}. ` +
      `RiskScore ${s.risk} из 16, ExtinctionScore ${s.ext} из 8. ` +
      'Рекомендации подготовлены ИИ-модулем (макет генерации) и требуют согласования с бортовыми протоколами.',
    steps: st.map(([title, detail], i) => ({
      n: String(i + 1).padStart(2, '0'),
      title,
      detail,
    })),
  };
}

/** §15.5 — «Допущения расчёта». */
export function notesOf(p: AnalysisParams, s: Scores): Note[] {
  const notes: Note[] = [];
  if (onOxygenBoundary(p.o2))
    notes.push({
      ref: '16.1',
      text: `O₂ = ${f1(p.o2)} % на неопределённой границе: OxygenRisk = ${s.t.o2}, OxygenDeficit = ${s.t.od}.`,
    });
  if (BOUNDARIES.flow.includes(p.flow as never))
    notes.push({
      ref: '16.1',
      text: `Поток ${f1(p.flow)} см/с на границе диапазонов: FlowRisk = ${s.t.flow}, LowFlowPenalty = ${s.t.lf}.`,
    });
  if (BOUNDARIES.temp.includes(p.temp as never))
    notes.push({ ref: '16.1', text: `Температура ${p.temp} °C на границе: TemperatureRisk = ${s.t.temp}.` });
  if (BOUNDARIES.time.includes(p.time as never))
    notes.push({ ref: '16.1', text: `Время ${p.time} с на границе: TimeRisk = ${s.t.time}.` });
  if (BOUNDARIES.thickness.includes(p.thickness as never))
    notes.push({
      ref: '16.1',
      text: `Толщина ${f1(p.thickness)} мм на границе: ThicknessBonus = ${s.t.th}.`,
    });
  if (p.material === 'other')
    notes.push({
      ref: '16.6',
      text: '«Другое»: базовый риск 2, описание в расчёте не учитывается.',
    });
  notes.push({
    ref: '16.4',
    text: 'Уровень «низкий» достижим только при RiskScore = 3 — шкала смещена к «высокому».',
  });
  notes.push({
    ref: '—',
    text: 'Гравитация учитывается как категория. Прогноз по уровню g и размеру пламени не строится.',
  });
  return notes;
}

