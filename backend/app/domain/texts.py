def recommendations(p: Params, s: Scores, sector_id: str, v: str) -> dict[str, Any]:
    """
    §15.3–15.4 — ЕДИНЫЙ генератор рекомендаций: окно рекомендаций, отчёт и
    блок «Рекомендуемые действия» (первые 3 шага) берут один и тот же список.
    """
    sec = SEC[sector_id]
    electrical = p['material'] == 'wire_insulation' or sector_id == 'ep'
    st: list[tuple[str, str]] = []

    if electrical:
        st.append(('Обесточьте линию и источник нагрева',
                   'Горение электропроводки поддерживается током: пока линия под напряжением, '
                   'тушение малоэффективно.'))
    elif s['t']['temp'] >= 2:
        st.append(('Отключите источник нагрева',
                   f'Температура {f1(p["temp"])} °C в зоне горения ускоряет прогрев материала.'))

    if s['t']['o2'] == 3 or s['t']['flow'] == 3:
        st.append(('Снизьте приток кислорода',
                   'Остановите вентиляцию сектора и подачу O₂, перекройте воздуховоды.'))

    if v != 'low':
        st.append(SECTOR_ACTION[sector_id])

    if s['level'] == 'high':
        st.append(('Изолируйте очаг',
                   'Отделите горючие материалы от очага, не допускайте переноса пламени '
                   'в соседние сектора.'))

    if v != 'low':
        st.append(('Примените подходящий способ тушения',
                   'Для электрооборудования — только неводное средство.' if electrical
                   else 'Выберите средство по типу материала.'))

    if s['extLevel'] == 'high' and v != 'low':
        st.append(('Не снимайте наблюдение после срыва пламени',
                   'Пламя нестабильно: возможно повторное воспламенение.'))

    if v == 'low':
        st.append(('Продолжайте наблюдение',
                   'Условия в секторе не поддерживают развитие пламени, действий не требуется.'))

    st.append(('Подтвердите приём отчёта на Земле',
               'Отчёт передаётся автоматически; сообщите о принятых мерах.'))

    return {
        'intro': (f'Сектор {sec["code"]}: {VERDICT_RU[v].lower()}. '
                  f'RiskScore {s["risk"]} из 16, ExtinctionScore {s["ext"]} из 8. '
                  'Рекомендации подготовлены ИИ-модулем (макет генерации) и требуют '
                  'согласования с бортовыми протоколами.'),
        'steps': [{'n': str(i + 1).zfill(2), 'title': title, 'detail': detail}
                  for i, (title, detail) in enumerate(st)],
    }


def notes_of(p: Params, s: Scores) -> list[dict[str, str]]:
    """§15.5 — «Допущения расчёта»."""
    notes: list[dict[str, str]] = []
    if on_oxygen_boundary(p['o2']):
        notes.append({'ref': '16.1',
                      'text': f'O₂ = {f1(p["o2"])} % на неопределённой границе: '
                              f'OxygenRisk = {s["t"]["o2"]}, OxygenDeficit = {s["t"]["od"]}.'})
    if p['flow'] in BOUNDARIES['flow']:
        notes.append({'ref': '16.1',
                      'text': f'Поток {f1(p["flow"])} см/с на границе диапазонов: '
                              f'FlowRisk = {s["t"]["flow"]}, LowFlowPenalty = {s["t"]["lf"]}.'})
    if p['temp'] in BOUNDARIES['temp']:
        notes.append({'ref': '16.1',
                      'text': f'Температура {f1(p["temp"])} °C на границе: '
                              f'TemperatureRisk = {s["t"]["temp"]}.'})
    if p['time'] in BOUNDARIES['time']:
        notes.append({'ref': '16.1',
                      'text': f'Время {f1(p["time"])} с на границе: TimeRisk = {s["t"]["time"]}.'})
    if p['thickness'] in BOUNDARIES['thickness']:
        notes.append({'ref': '16.1',
                      'text': f'Толщина {f1(p["thickness"])} мм на границе: '
                              f'ThicknessBonus = {s["t"]["th"]}.'})
    if p['material'] == 'other':
        notes.append({'ref': '16.6',
                      'text': '«Другое»: базовый риск 2, описание в расчёте не учитывается.'})
    notes.append({'ref': '16.4',
                  'text': 'Уровень «низкий» достижим только при RiskScore = 3 — '
                          'шкала смещена к «высокому».'})
    notes.append({'ref': '—',
                  'text': 'Гравитация учитывается как категория. '
                          'Прогноз по уровню g и размеру пламени не строится.'})
    return notes
