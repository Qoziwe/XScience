def explain(p: Params, s: Scores) -> dict[str, str]:
    """§15.1 — объяснение риска и затухания."""
    t = s['t']
    parts: list[str] = []
    if t['mat'] == 3:
        parts.append(f'{MAT[p["material"]]["label"].lower()} — легковоспламеняемый материал')
    if t['o2'] == 3:
        parts.append(f'кислород выше нормы ({f1(p["o2"])} %)')
    if t['flow'] == 3:
        parts.append(f'поток {f1(p["flow"])} см/с активно подпитывает пламя')
    if t['temp'] >= 2:
        parts.append(f'высокая температура в зоне горения ({f1(p["temp"])} °C)')
    if t['time'] >= 2:
        parts.append(f'длительное горение ({f1(p["time"])} с)')
    if t['grav'] == 1:
        parts.append('микрогравитация повышает неопределённость поведения пламени')

    why = (f'Риск повышают: {"; ".join(parts)}.' if parts else
           'Все составляющие на минимальных значениях — условия не поддерживают развитие пламени.')

    e: list[str] = []
    if t['od'] >= 2:
        e.append(f'недостаток кислорода ({f1(p["o2"])} %)')
    if t['lf'] >= 1:
        e.append('отсутствие потока' if p['flow'] == 0 else 'слабый поток')
    if t['th'] >= 2:
        e.append(f'тонкий материал ({f1(p["thickness"])} мм)')

    tail = ' — ' + ', '.join(e) if e else ', факторов затухания нет'
    why_ext = f'Затухание: {EXT_LEVEL_RU[s["extLevel"]].lower()} вероятность{tail}.'
    return {'why': why, 'why_ext': why_ext}


def summary_of(s: Scores) -> str:
    """§15.2 — заключение."""
    if s['level'] == 'high' and s['extLevel'] == 'high':
        return ('Горение нестабильно: условия одновременно поддерживают быстрое распространение '
                'и срыв пламени. Нужен контроль — после срыва возможно повторное воспламенение.')
    if s['level'] == 'high':
        return ('Сочетание материала, кислорода и потока создаёт условия для быстрого '
                'распространения пламени. Затухание маловероятно — требуется вмешательство.')
    if s['level'] == 'medium':
        return ('Отдельные параметры повышают опасность, но условия для устойчивого быстрого '
                'горения не сложились. Достаточно наблюдения и устранения ведущего фактора.')
    return ('Все составляющие на минимальных значениях. '
            'Угрозы для сектора при текущих показаниях нет.')


