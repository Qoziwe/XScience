"""
Report for Earth. Port of frontend/src/domain/report.ts (§11).
The document is assembled once, when the analysis is created, from the stored
texts, so it never changes after the fact when the rules (§15) are edited.
Only the "Transmission" line changes — it reflects the current send status (§11.4).
"""
from __future__ import annotations

from typing import Any

from .format import f1, pad, report_no
from .reference import (
    EXT_LEVEL_RU, MAT, RISK_LEVEL_RU, SEC, VERDICT_RU, gravity_ru, sent_full,
)

BASE_LIMITS = ('The assessment is built from the rules in section 14. The verdict is the '
               'rule-based calculation; the ML model forecast is not part of it (§17.1). '
               'NASA ranges have not been verified. Gravity is accounted for as a category. '
               'Recommendations are advisory in nature.')


def limits(texts_source: str, texts_model: str) -> str:
    """§11.2 — "Limitations". States plainly what generated the report's texts."""
    if texts_source == 'llm':
        origin = (f'Texts and recommendations were generated by an AI model ({texts_model}) '
                  'from the calculation data; it does not change the scores, levels, or verdict.')
    else:
        origin = ('Texts and recommendations were generated by the deterministic rules in '
                  'section 15; no AI model was used.')
    return f'{BASE_LIMITS} {origin}'


def _conclusion(verdict_label: str, summary: str) -> str:
    """Verdict + conclusion, without duplication if the text already starts with the verdict."""
    head = verdict_label.rstrip('.').lower()
    if summary.strip().lower().startswith(head):
        return summary.strip()
    return f'{verdict_label}. {summary}"'.rstrip('"')

#: Metadata key that depends on the current transmission status.
SENT_KEY = 'Transmission'


def report_doc(rec: dict[str, Any]) -> dict[str, Any]:
    """
    Report document (§11.2) built from the full analysis record (§4.2).
    `rec` — the record with fields p/risk/ext/level/extLevel/v/conf/ts/texts.
    """
    p = rec['p']
    sec = SEC[rec['sector']]
    texts = rec['texts']
    params = (f'{MAT[p["material"]]["label"]}, {f1(p["thickness"])} mm; '
              f'O₂ {f1(p["o2"])} %; flow {f1(p["flow"])} cm/s; '
              f'{f1(p["temp"])} °C; {f1(p["time"])} s; {gravity_ru(p["gravity"])}.')
    return {
        'no': report_no(rec['id']),
        'analysisId': rec['id'],
        'title': f'{sec["code"]} · {sec["name"]}',
        'verdict': VERDICT_RU[rec['v']],
        'verdictKey': rec['v'],
        'meta': [
            {'k': 'Sector', 'v': f'{sec["code"]} · {sec["name"]}'},
            {'k': 'Generated', 'v': rec['ts']},
            {'k': 'Author', 'v': 'AI status module (generation mock-up)'},
            {'k': SENT_KEY, 'v': sent_full(rec.get('sent'))},
            {'k': 'Comm channel', 'v': 'mock-up, no actual transmission'},
            {'k': 'Analysis', 'v': '#' + pad(rec['id'])},
        ],
        'sections': [
            {'h': 'Conclusion',
             't': _conclusion(VERDICT_RU[rec['v']], texts['summary'])},
            {'h': 'Input Parameters', 't': params},
            {'h': 'Scores',
             't': (f'RiskScore {rec["risk"]} out of 16 '
                   f'({RISK_LEVEL_RU[rec["level"]].lower()}); '
                   f'ExtinctionScore {rec["ext"]} out of 8 '
                   f'({EXT_LEVEL_RU[rec["extLevel"]].lower()}). '
                   f'Assessment confidence {rec["conf"]} %.')},
            {'h': 'Limitations', 't': limits(rec.get('texts_source', 'rules'),
                                             rec.get('texts_model', 'rules-v0.1'))},
        ],
        'intro': texts['rec_intro'],
        'steps': texts['rec_steps'],
    }


def with_sent(doc: dict[str, Any], sent: str | None) -> dict[str, Any]:
    """Updates the "Transmission" line in the stored document (§11.4)."""
    out = dict(doc)
    out['meta'] = [{'k': m['k'], 'v': sent_full(sent)} if m['k'] == SENT_KEY else m
                   for m in doc['meta']]
    return out


def report_txt(d: dict[str, Any]) -> str:
    """§11.3 — TXT format. Served via GET /api/reports/{id}.txt"""
    lines = [
        f'REPORT {d["no"]}',
        f'Sector: {d["title"]}',
        f'Conclusion: {d["verdict"]}',
        '',
        *[f'{m["k"]}: {m["v"]}' for m in d['meta']],
        '',
    ]
    for s in d['sections']:
        lines += [s['h'].upper(), s['t'], '']
    lines += ['RECOMMENDATIONS', d['intro']]
    lines += [f'{s["n"]}. {s["title"]} — {s["detail"]}' for s in d['steps']]
    return '\n'.join(lines)


CSV_HEAD = ('id,time,sector,material_type,thickness_mm,gravity,oxygen_percent,air_flow_cm_s,'
            'temperature_C,time_s,risk_score,risk_level,extinction_score,extinction_probability')


def history_csv(hist: list[dict[str, Any]]) -> str:
    """§16.2 — history export to CSV (same column order as the client)."""
    rows = []
    for r in hist:
        p = r['p']
        rows.append(','.join(str(x) for x in [
            r['id'], r['ts'], r['sector'], p['material'], f1(p['thickness']), p['gravity'],
            f1(p['o2']), f1(p['flow']), f1(p['temp']), f1(p['time']),
            r['risk'], r['level'], r['ext'], r['extLevel'],
        ]))
    return '\n'.join([CSV_HEAD, *rows])
